"""Write js/language-momentum-data.js for the Programming Language Momentum Checker.
Usage: python3 export_tool_data.py PATH/TO/js/language-momentum-data.js
Run analysis.py first."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
OUT = HERE / "data/processed"
sig = pd.read_csv(OUT / "momentum-by-language-and-country.csv")
fc = pd.read_csv(OUT / "forecast-2028-relative-usage.csv").set_index("language")
now = pd.read_csv(OUT / "trending-now-last-12-months.csv").set_index("language")
adz = pd.read_csv(HERE / "data/inputs/adzuna-it-jobs-2026-11-05.csv")
hn = pd.read_csv(OUT / "hn-share-by-year.csv", index_col=0)

pct = lambda v: None if pd.isna(v) else round(100 * (np.exp(v) - 1), 1)
r1 = lambda v, k=1: None if pd.isna(v) else round(float(v), k)
geo_map = {"WORLD": "world", "GB": "uk", "US": "us", "IN": "in"}
data = {"updated": "2026-11-05", "langs": {}, "geos": {}}
for g, sub in sig.groupby("geo"):
    rows = {}
    for _, r in sub.iterrows():
        rows[r.language] = dict(rank=None if pd.isna(r["rank"]) else int(r["rank"]), score=r1(r.momentum, 2), verdict=r.verdict,
                                usage=pct(r.usage), hiring=pct(r.hiring), learning=pct(r.learning), interest=pct(r.interest),
                                ghShare=r1(100 * r.share_after, 2) if not pd.isna(r.share_after) else None,
                                ghPushers=None if pd.isna(r.pushers_after) else int(round(r.pushers_after, -2)),
                                usedPct=r1(r.used_2026), wantPct=r1(r.want_2026), surveyN=None if pd.isna(r.survey_n_2026) else int(r.survey_n_2026))
    data["geos"][geo_map[g]] = rows
for L in sig.language.unique():
    d = {"hn2026": r1(hn.loc[2026, L]) if L in hn.columns else None,
         "hn2015": r1(hn.loc[2015, L]) if L in hn.columns else None}
    if L in fc.index:
        f = fc.loc[L]
        d["forecast"] = dict(mid=r1(f.rel_growth_pct), lo=r1(f.lo), hi=r1(f.hi), pGain=round(float(f.p_gain), 2))
    if L in now.index and not pd.isna(now.loc[L, "score"]):
        d["now"] = dict(score=r1(now.loc[L, "score"], 2), up=int(now.loc[L, "n_up"]), of=int(now.loc[L, "n_signals"]))
    data["langs"][L] = d
data["jobs"] = {}
for _, r in adz.iterrows():
    data["jobs"].setdefault(geo_map.get(r.country, r.country.lower()) if r.country != "GB" else "uk", {})[r.language] = dict(
        ads=int(r.ads), salary=int(r.mean_advertised_salary), currency=r.currency)
js = ("// Generated by export_tool_data.py (truthwithdata/analysis, programming-languages). Do not edit by hand.\n"
      "// Sources: GitHub Innovation Graph (CC0), Stack Overflow Developer Survey (ODbL), Hacker News 'Who is hiring?',\n"
      "// Google Trends, and job ads and salaries from The Adzuna API (https://www.adzuna.co.uk/).\n"
      "window.LANG_MOMENTUM = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
Path(sys.argv[1]).write_text(js)
print(sys.argv[1], len(js))
